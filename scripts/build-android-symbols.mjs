/**
 * Builds components/os/android/symbols.generated.ts: the Material Symbols Rounded paths (weight 400, grade 0, opsz 24,
 * outline + filled) for exactly the symbol names the Android code uses. Names are found by scanning
 * components/os/android for string literals and <Symbol>name</Symbol> children that are known symbol names, so the
 * Android chunk carries only the glyphs it draws. Run after adding a new glyph: node scripts/build-android-symbols.mjs
 */
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

const ROOT = 'components/os/android';
async function sources(dir) {
  const files = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) files.push(...(await sources(path)));
    else if (/\.tsx?$/.test(entry.name) && !entry.name.includes('.generated.')) files.push(path);
  }
  return files;
}
const used = new Set();
for (const file of await sources(ROOT)) {
  const text = await readFile(file, 'utf8');
  for (const match of text.matchAll(/'([a-z][a-z0-9_]*)'|>([a-z][a-z0-9_]*)</g)) used.add(match[1] ?? match[2]);
}
