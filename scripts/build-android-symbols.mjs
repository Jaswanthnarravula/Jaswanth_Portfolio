const base = 'https://raw.githubusercontent.com/google/material-design-icons/master/symbols/web';
const pathOf = (svg) => [...svg.matchAll(/ d="([^"]+)"/g)].map((m) => m[1]).join(' ');
const out = {};
const missing = [];
await Promise.all(
  NAMES.map(async (name) => {
    const [a, b] = await Promise.all([
      fetch(`${base}/${name}/materialsymbolsrounded/${name}_24px.svg`),
      fetch(`${base}/${name}/materialsymbolsrounded/${name}_fill1_24px.svg`),
    ]);
    if (!a.ok) {
      missing.push(name);
      return;
    }
    const outline = pathOf(await a.text());
    const filled = b.ok ? pathOf(await b.text()) : outline;
    out[name] = filled === outline ? [outline] : [outline, filled];
  }),
);
const keys = Object.keys(out).sort();
const body = keys.map((k) => `  ${k}: ${JSON.stringify(out[k])},`).join('\n');
await writeFile(
  process.argv[2] ?? 'components/os/android/symbols.generated.ts',
  `/**
 * Material Symbols Rounded (weight 400, grade 0, optical size 24), outline and filled paths, viewBox 0 -960 960 960.
 * Source: github.com/google/material-design-icons (symbols/web/<name>/materialsymbolsrounded) — Apache License 2.0,
 * © Google. Generated by scripts/build-android-symbols.mjs; do not edit by hand.
 */
export const SYMBOL_PATHS = {
${body}
} as const satisfies Record<string, readonly [string] | readonly [string, string]>;

export type SymbolName = keyof typeof SYMBOL_PATHS;
`,
);
