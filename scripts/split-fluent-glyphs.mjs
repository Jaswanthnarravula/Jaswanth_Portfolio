/**
 * Splits the generated Fluent glyphs by who loads them (shared/10: the Windows shell ≤ 38 KB gz). A module shared by
 * several chunks is bundled whole, so one glyph module made the shell's first load carry every app's icons. Glyphs
 * the shell's first chunk uses stay in `fluent.generated.ts`; the rest (apps, on-demand surfaces) go to
 * `fluent.apps.generated.ts`, and every importer is pointed at the right file. Idempotent; run after
 * scripts/fetch-fluent-icons.mjs (which calls it) or by hand:
 *   node scripts/split-fluent-glyphs.mjs
 */
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const dir = resolve(root, 'components/os/windows');
const SHELL_FILE = join(dir, 'fluent.generated.ts');
const APPS_FILE = join(dir, 'fluent.apps.generated.ts');

/** The files in the shell's first chunk (everything else is an app or an on-demand surface). */
const SHELL = [
  'Shell.tsx',
  'icons.tsx',
  'model.ts',
  'slots.tsx',
  'shell-context.tsx',
  'window/Window.tsx',
  'apps/AppBody.tsx',
  'surfaces/Taskbar.tsx',
  'surfaces/Desktop.tsx',
  'surfaces/Notifications.tsx',
  'surfaces/LockScreen.tsx',
  'surfaces/WinMenu.tsx',
  'surfaces/Boot.tsx',
].map((file) => join(dir, file));

const IMPORT = /import\s*\{([^}]*)\}\s*from\s*'(\.{1,2}(?:\/\.\.)*)\/fluent(?:\.apps)?\.generated';\n/g;

async function files(folder) {
  const out = [];
  for (const entry of await readdir(folder, { withFileTypes: true })) {
    const path = join(folder, entry.name);
    if (entry.isDirectory()) out.push(...(await files(path)));
    else if (/\.(ts|tsx)$/.test(entry.name) && !entry.name.includes('fluent')) out.push(path);
  }
  return out;
}

const names = (list) =>
  list
    .split(',')
    .map((part) => part.trim())
    .filter(Boolean);

// 1. Every glyph block from both generated files.
const blocks = new Map();
let header = '';
for (const file of [SHELL_FILE, APPS_FILE]) {
  let text;
  try {
    text = await readFile(file, 'utf8');
  } catch {
    continue;
  }
  if (file === SHELL_FILE) header = text.slice(0, text.indexOf('/** ', text.indexOf('export interface Glyph')));
  // One doc comment + one export per glyph, on one line or (if a formatter touched the file) several.
  for (const match of text.matchAll(/(\/\*\* [^*]+ \*\/\nexport const (fl\w+): Glyph = \{[\s\S]*?\};)/g))
    blocks.set(match[2], match[1]);
}
if (!header) throw new Error('fluent.generated.ts has no header');
if (!blocks.size) throw new Error('no glyphs found');

// 2. Which glyphs the shell's first chunk uses.
const sources = await files(dir);
const used = new Map(); // file → [names]
for (const file of sources) {
  const text = await readFile(file, 'utf8');
  const list = [...text.matchAll(IMPORT)].flatMap((match) => names(match[1]).filter((name) => name.startsWith('fl')));
  if (list.length) used.set(file, list);
}
const shellGlyphs = new Set(SHELL.flatMap((file) => used.get(file) ?? []));

// 3. Write the two modules.
const pick = (set) =>
  [...blocks.keys()]
    .filter(set)
    .sort()
    .map((name) => blocks.get(name))
    .join('\n');
await writeFile(SHELL_FILE, `${header}${pick((name) => shellGlyphs.has(name))}\n`);
await writeFile(
  APPS_FILE,
  `/**
 * Generated by scripts/fetch-fluent-icons.mjs + scripts/split-fluent-glyphs.mjs — do not edit.
 * The glyphs only apps and on-demand surfaces use (their own chunks); the shell's are in ./fluent.generated.
 * Fluent UI System Icons (@fluentui/svg-icons), © Microsoft Corporation, MIT License.
 */
import type { Glyph } from './fluent.generated';

${pick((name) => !shellGlyphs.has(name))}
`,
);

// 4. Point every importer at the right module.
for (const [file, list] of used) {
  let text = await readFile(file, 'utf8');
  const prefix = relative(dirname(file), dir).replace(/\\/g, '/') || '.';
  const base = prefix.startsWith('.') ? prefix : `./${prefix}`;
  const typeNames = [...text.matchAll(IMPORT)].flatMap((match) =>
    names(match[1]).filter((name) => !name.startsWith('fl')),
  );
  text = text.replace(IMPORT, '');
  const shellNames = list.filter((name) => shellGlyphs.has(name));
  const appNames = list.filter((name) => !shellGlyphs.has(name));
  const lines = [];
  if (shellNames.length || typeNames.length)
    lines.push(`import { ${[...shellNames, ...typeNames].join(', ')} } from '${base}/fluent.generated';`);
  if (appNames.length) lines.push(`import { ${appNames.join(', ')} } from '${base}/fluent.apps.generated';`);
  // Insert before the first relative import (the local imports read alphabetically), else after the last import.
  const importLines = [...text.matchAll(/^import [^;]+;\n/gm)];
  const firstLocal = importLines.find((match) => /from '\.{1,2}\//.test(match[0]));
  const last = importLines[importLines.length - 1];
  const at = firstLocal ? firstLocal.index : last ? last.index + last[0].length : 0;
  text = text.slice(0, at) + lines.join('\n') + '\n' + text.slice(at);
  await writeFile(file, text);
}
console.log(`[fluent] shell ${shellGlyphs.size} glyphs · apps ${blocks.size - shellGlyphs.size} glyphs`);
